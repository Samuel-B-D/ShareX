using System.Collections.ObjectModel;
using System.Diagnostics.CodeAnalysis;

namespace ShareX.Copying;

/// <summary>
/// Generates a deep copy implementation (<see cref="IDeepCopyable"/>) for this partial class and every partial class
/// deriving from it. The copy is made with MemberwiseClone, then every reference member is copied recursively:
/// arrays, List, Dictionary, HashSet and ObservableCollection are copied element by element, members whose type is
/// deep copyable are copied, delegates and events are cleared, strings and value types are kept.
/// Generated by ShareX.Roslyn (DeepCopyGenerator) instead of the former reflection based copy, which lost private
/// fields of framework types under trimming and NativeAOT.
/// </summary>
[AttributeUsage(AttributeTargets.Class, Inherited = true)]
public sealed class GenerateDeepCopyAttribute : Attribute
{
}

/// <summary>
/// The member is intentionally shared between the original and the copy (immutable or externally owned object).
/// Silences the ShareX.Roslyn warning for reference members that are not deep copyable.
/// </summary>
[AttributeUsage(AttributeTargets.Field | AttributeTargets.Property)]
public sealed class ShallowCopyAttribute : Attribute
{
}

public interface IDeepCopyable
{
    object DeepCopyObject();
}

/// <summary>Runtime helpers used by the generated deep copy code.</summary>
public static class DeepCopy
{
    /// <summary>Deep copy of <paramref name="value"/> when it is deep copyable; arrays are cloned; other objects are returned as is.</summary>
    [return: NotNullIfNotNull(nameof(value))]
    public static T? Copy<T>(T? value)
    {
        return value switch
        {
            null => default,
            IDeepCopyable copyable => (T)copyable.DeepCopyObject(),
            Array array => (T)(object)CopyArray(array),
            _ => value
        };
    }

    [return: NotNullIfNotNull(nameof(value))]
    public static T? Object<T>(T? value) where T : class
    {
        return Copy(value);
    }

    [return: NotNullIfNotNull(nameof(source))]
    public static T[]? ArrayOf<T>(T[]? source, Func<T, T> copyItem)
    {
        if (source == null) return null;

        T[] result = new T[source.Length];

        for (int i = 0; i < source.Length; i++)
        {
            result[i] = copyItem(source[i]);
        }

        return result;
    }

    [return: NotNullIfNotNull(nameof(source))]
    public static List<T>? ListOf<T>(List<T>? source, Func<T, T> copyItem)
    {
        if (source == null) return null;

        List<T> result = new List<T>(source.Count);

        foreach (T item in source)
        {
            result.Add(copyItem(item));
        }

        return result;
    }

    [return: NotNullIfNotNull(nameof(source))]
    public static ObservableCollection<T>? ObservableCollectionOf<T>(ObservableCollection<T>? source, Func<T, T> copyItem)
    {
        if (source == null) return null;

        ObservableCollection<T> result = new ObservableCollection<T>();

        foreach (T item in source)
        {
            result.Add(copyItem(item));
        }

        return result;
    }

    [return: NotNullIfNotNull(nameof(source))]
    public static HashSet<T>? HashSetOf<T>(HashSet<T>? source, Func<T, T> copyItem)
    {
        if (source == null) return null;

        HashSet<T> result = new HashSet<T>(source.Comparer);

        foreach (T item in source)
        {
            result.Add(copyItem(item));
        }

        return result;
    }

    [return: NotNullIfNotNull(nameof(source))]
    public static Dictionary<TKey, TValue>? DictionaryOf<TKey, TValue>(Dictionary<TKey, TValue>? source, Func<TKey, TKey> copyKey,
        Func<TValue, TValue> copyValue) where TKey : notnull
    {
        if (source == null) return null;

        Dictionary<TKey, TValue> result = new Dictionary<TKey, TValue>(source.Count, source.Comparer);

        foreach (KeyValuePair<TKey, TValue> pair in source)
        {
            result.Add(copyKey(pair.Key), copyValue(pair.Value));
        }

        return result;
    }

    private static Array CopyArray(Array source)
    {
        Array result = (Array)source.Clone();

        if (result.Rank == 1)
        {
            for (int i = 0; i < result.Length; i++)
            {
                object? item = result.GetValue(i);

                if (item is IDeepCopyable copyable)
                {
                    result.SetValue(copyable.DeepCopyObject(), i);
                }
            }
        }

        return result;
    }
}
